#!/usr/bin/env python3
"""Generate ``docs/commands.md``, the command reference, from the real command tree.

Discord users meet Aha through slash commands, so those are its API. The reference is built by
loading every cog into a bot and reading the commands back, so it cannot disagree with the bot;
``tests/test_command_docs.py`` fails when the committed file is out of date.

    uv run python -m scripts.gen_command_docs           # rewrite docs/commands.md
    uv run python -m scripts.gen_command_docs --check   # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path
from typing import Any

import discord
from discord import app_commands

from aha.bot import COG_MODULES, AhaBot
from aha.config import Settings

__all__ = ["OUTPUT", "build_markdown", "main"]

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "commands.md"

#: Categories in the order ``/help`` lists them first; any other follows alphabetically.
CATEGORY_ORDER = ("Info", "Fun", "Admin")

HEADER = """\
# Command reference

<!-- Generated by `uv run python -m scripts.gen_command_docs`. Do not edit by hand: a test fails
     when this file does not match the bot's real commands. -->

Aha is used through Discord's slash commands (there are no message commands: the bot does not read
messages). This is every command, generated from the bot itself. Command names, option descriptions
and replies are translated where the catalogue has a translation (see [i18n.md](i18n.md)).

Replies to commands that show personal data or settings are only visible to you. Commands that need
a database (`/remind`, `/watch`, `/config` and others) say so when the bot runs without one. For the
HTTP endpoints of the bot process itself (probes and metrics) see [openapi.yaml](openapi.yaml).
"""


async def _bot() -> AhaBot:
    bot = AhaBot(Settings(token="docs-only"))
    for module in COG_MODULES:  # not the owner-only /sync, which only a dev guild has
        await bot.load_extension(module)
    return bot


def _permissions(permissions: discord.Permissions | None) -> str | None:
    if permissions is None or not permissions.value:
        return None
    names = [name.replace("_", " ").title() for name, held in permissions if held]
    return ", ".join(names)


def _option_row(parameter: Any) -> str:
    choices = "; ".join(
        f"`{choice.value}`"
        if choice.name == str(choice.value)
        else f"`{choice.value}` ({choice.name})"
        for choice in parameter.choices
    )
    notes = f" Choices: {choices}." if choices else ""
    required = "yes" if parameter.required else "no"
    return f"| `{parameter.display_name}` | {required} | {parameter.description}{notes} |"


def _slash(command: app_commands.Command[Any, ..., Any], bot: AhaBot) -> tuple[str, str]:
    """The category and the Markdown section of one slash command."""
    text_command = bot.get_command(command.qualified_name)
    category = str(text_command.extras.get("category", "Other")) if text_command else "Other"
    options = " ".join(
        f"<{p.display_name}>" if p.required else f"[{p.display_name}]" for p in command.parameters
    )
    lines = [f"### `/{command.qualified_name}`", "", command.description, ""]
    if command.parameters:
        lines += ["| Option | Required | Description |", "|--------|----------|-------------|"]
        lines += [_option_row(p) for p in command.parameters]
        lines += ["", f"Usage: `/{command.qualified_name} {options}`", ""]
    facts: list[str] = []
    cooldown = getattr(text_command, "cooldown", None)
    if cooldown is not None:
        facts.append(f"cooldown: {cooldown.rate} per {cooldown.per:g} s per user")
    if command.guild_only:
        facts.append("servers only")
    needs = _permissions(command.default_permissions)
    if needs:
        facts.append(f"needs: {needs}")
    if facts:
        lines += [f"*{'; '.join(facts)}.*", ""]
    return category, "\n".join(lines)


def _menu(command: app_commands.ContextMenu) -> str:
    kind = "message" if command.type is discord.AppCommandType.message else "user"
    where = f"Apps → {command.name}"
    return f"### {command.name} ({kind} menu)\n\nRight-click a {kind}: **{where}**.\n"


def build_markdown() -> str:
    """The whole reference as Markdown (deterministic, so it can be compared with the file)."""
    bot = asyncio.run(_bot())
    sections: dict[str, list[tuple[str, str]]] = {}
    for command in bot.tree.walk_commands():
        if isinstance(command, app_commands.Command):
            category, text = _slash(command, bot)
            sections.setdefault(category, []).append((command.qualified_name, text))
    menus = [
        _menu(command)
        for kind in (discord.AppCommandType.message, discord.AppCommandType.user)
        for command in sorted(bot.tree.get_commands(type=kind), key=lambda c: c.name)
        if isinstance(command, app_commands.ContextMenu)
    ]
    ordered = sorted(
        sections,
        key=lambda c: (CATEGORY_ORDER.index(c) if c in CATEGORY_ORDER else len(CATEGORY_ORDER), c),
    )
    parts = [HEADER]
    for category in ordered:
        parts.append(f"## {category}\n")
        parts.extend(text for _, text in sorted(sections[category]))
    if menus:
        parts.append("## Context menus\n")
        parts.extend(menus)
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the reference, or with ``--check`` verify it. Returns the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)
    text = build_markdown()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date; run: uv run python -m scripts.gen_command_docs")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
